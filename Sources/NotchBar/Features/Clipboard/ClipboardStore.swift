import AppKit
import SwiftUI

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, link, image, file }
    var id = UUID()
    var kind: Kind
    var text: String?
    var imageFile: String?
    var files: [String]?
    var date: Date
    var sourceBundle: String?
    var pinned = false

    var title: String {
        switch kind {
        case .text: return "Text"
        case .link: return "Link"
        case .image: return "Image"
        case .file: return (files?.count ?? 0) > 1 ? "\(files!.count) Files" : "File"
        }
    }
}

/// Clipboard history, saved in Application Support.
///
/// It skips anything a password manager marks as concealed or transient, and anything copied
/// while a password manager is the front app.
@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published var isPaused: Bool { didSet { UserDefaults.standard.set(isPaused, forKey: "clipboardPaused") } }
    @Published private(set) var lastCopiedID: UUID?

    private let pasteboard = NSPasteboard.general
    private var changeCount: Int
    /// macOS has no clipboard-changed notification, so the change counter is checked twice a
    /// second. Reading it is a single cheap call, and the timer stops while the screen sleeps.
    private lazy var watcher = EfficientTimer(interval: 0.5, tolerance: 0.25) { [weak self] in self?.poll() }

    /// Off while the Clipboard tab is hidden.
    var isEnabled = true {
        didSet {
            guard isEnabled != oldValue else { return }
            changeCount = pasteboard.changeCount
            isEnabled ? watcher.start() : watcher.stop()
        }
    }
    private let limit = 60
    private let persist: Bool

    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
    ]
    private static let skippedApps: Set<String> = [
        "com.apple.keychainaccess", "com.apple.Passwords", "com.1password.1password", "com.agilebits.onepassword7",
        "com.bitwarden.desktop", "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal",
    ]

    static var folder: URL {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        return base.appendingPathComponent("NotchBar/Clipboard", isDirectory: true)
    }
    private static var indexURL: URL { folder.appendingPathComponent("history.json") }

    init(persist: Bool = true) {
        self.persist = persist
        isPaused = UserDefaults.standard.bool(forKey: "clipboardPaused")
        changeCount = NSPasteboard.general.changeCount
        guard persist else { return }
        if let data = try? Data(contentsOf: Self.indexURL),
           let saved = try? JSONDecoder().decode([ClipItem].self, from: data) {
            items = saved
        }
    }

    func start() {
        if isEnabled { watcher.start() }
    }

    /// Test hook for snapshots.
    func setPreview(_ items: [ClipItem]) { self.items = items }

    private func poll() {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        guard !isPaused else { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let source, Self.skippedApps.contains(source) { return }
        guard let item = capture(source: source) else { return }
        insert(item)
    }

    private func capture(source: String?) -> ClipItem? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return ClipItem(kind: .file, files: urls.map(\.path), date: Date(), sourceBundle: source)
        }
        if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            let isLink = !trimmed.contains(where: \.isWhitespace) && URL(string: trimmed)?.scheme.map { ["http", "https"].contains($0) } == true
            return ClipItem(kind: isLink ? .link : .text, text: String(string.prefix(20_000)), date: Date(), sourceBundle: source)
        }
        if let image = NSImage(pasteboard: pasteboard), let file = saveImage(image) {
            return ClipItem(kind: .image, imageFile: file, date: Date(), sourceBundle: source)
        }
        return nil
    }

    private func insert(_ item: ClipItem) {
        var new = item
        // Copying the same thing again moves it to the front instead of duplicating it.
        if let i = items.firstIndex(where: { $0.kind == item.kind && $0.text == item.text && $0.files == item.files && item.kind != .image }) {
            new.pinned = items[i].pinned
            new.id = items[i].id
            items.remove(at: i)
        }
        withAnimation(.spring(response: 0.4, dampingFraction: 0.82)) { items.insert(new, at: 0) }
        trim()
        save()
    }

    private func trim() {
        var unpinned = 0
        var kept: [ClipItem] = []
        for item in items {
            if item.pinned { kept.append(item); continue }
            unpinned += 1
            if unpinned <= limit { kept.append(item) } else { removeFile(item) }
        }
        items = kept
    }

    // MARK: Actions

    func copy(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.kind {
        case .text, .link:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            if let file = item.imageFile, let image = NSImage(contentsOf: Self.folder.appendingPathComponent(file)) {
                pasteboard.writeObjects([image])
            }
        case .file:
            pasteboard.writeObjects((item.files ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        }
        // Don't record our own write as a new item, but do move it to the front.
        changeCount = pasteboard.changeCount
        if let i = items.firstIndex(of: item) {
            var moved = items.remove(at: i)
            moved.date = Date()
            withAnimation(.spring(response: 0.4, dampingFraction: 0.82)) { items.insert(moved, at: 0) }
            save()
        }
        lastCopiedID = item.id
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        withAnimation(.spring(response: 0.35, dampingFraction: 0.8)) { items[i].pinned.toggle() }
        save()
    }

    func delete(_ item: ClipItem) {
        removeFile(item)
        withAnimation(.spring(response: 0.35, dampingFraction: 0.85)) { items.removeAll { $0.id == item.id } }
        save()
    }

    func clearUnpinned() {
        items.filter { !$0.pinned }.forEach(removeFile)
        withAnimation(.spring(response: 0.35, dampingFraction: 0.85)) { items.removeAll { !$0.pinned } }
        save()
    }

    /// Removes everything, pinned items included.
    func clearAll() {
        items.forEach(removeFile)
        withAnimation(.spring(response: 0.35, dampingFraction: 0.85)) { items.removeAll() }
        save()
    }

    var hasPinned: Bool { items.contains { $0.pinned } }

    // MARK: Storage

    private var thumbnails: [String: NSImage] = [:]
    var previewImages: [String: NSImage] = [:]

    func image(for item: ClipItem) -> NSImage? {
        guard let file = item.imageFile else { return nil }
        if let cached = thumbnails[file] ?? previewImages[file] { return cached }
        let image = NSImage(contentsOf: Self.folder.appendingPathComponent(file))
        thumbnails[file] = image
        return image
    }

    private func saveImage(_ image: NSImage) -> String? {
        guard persist else { return nil }
        // Keep history light: store a downscaled PNG.
        let maxSide: CGFloat = 1200
        let scale = min(1, maxSide / max(image.size.width, image.size.height, 1))
        let size = NSSize(width: max(1, image.size.width * scale), height: max(1, image.size.height * scale))
        guard let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: Int(size.width), pixelsHigh: Int(size.height),
                                         bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                                         colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0) else { return nil }
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
        image.draw(in: NSRect(origin: .zero, size: size))
        NSGraphicsContext.restoreGraphicsState()
        guard let png = rep.representation(using: .png, properties: [:]) else { return nil }
        let name = UUID().uuidString + ".png"
        try? FileManager.default.createDirectory(at: Self.folder, withIntermediateDirectories: true)
        guard (try? png.write(to: Self.folder.appendingPathComponent(name))) != nil else { return nil }
        return name
    }

    private func removeFile(_ item: ClipItem) {
        guard let file = item.imageFile else { return }
        try? FileManager.default.removeItem(at: Self.folder.appendingPathComponent(file))
    }

    private func save() {
        guard persist else { return }
        try? FileManager.default.createDirectory(at: Self.folder, withIntermediateDirectories: true)
        if let data = try? JSONEncoder().encode(items) {
            try? data.write(to: Self.indexURL, options: .atomic)
        }
    }
}
